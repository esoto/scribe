import XCTest

final class PasteCoreTests: XCTestCase {
    class FakePasteboard: PasteboardLike {
        private(set) var items: [PasteboardItemData]
        private var count = 1

        init(items: [PasteboardItemData] = [["public.utf8-plain-text": Data("old stuff".utf8)]]) {
            self.items = items
        }

        func snapshot() -> [PasteboardItemData]? {
            items.isEmpty ? nil : items
        }

        func restore(_ items: [PasteboardItemData]) {
            self.items = items
            count += 1
        }

        func setTransient(_ s: String) {
            items = [[
                "public.utf8-plain-text": Data(s.utf8),
                "org.nspasteboard.TransientType": Data(),
                "org.nspasteboard.AutoGeneratedType": Data(),
            ]]
            count += 1
        }

        func changeCount() -> Int {
            count
        }

        /// Simulates the user copying something else.
        func userCopies(_ items: [PasteboardItemData]) {
            self.items = items
            count += 1
        }
    }

    class FakeScheduler {
        private(set) var delays: [Double] = []
        private var jobs: [() -> Void] = []

        var pending: Int { jobs.count }

        func schedule(_ delay: Double, _ job: @escaping () -> Void) {
            delays.append(delay)
            jobs.append(job)
        }

        func fire() {
            guard !jobs.isEmpty else { return }
            jobs.removeFirst()()
        }

        func fireAll() {
            while !jobs.isEmpty { fire() }
        }
    }

    private let text = "public.utf8-plain-text"

    func test_paste_sets_posts_and_restores() throws {
        let pb = FakePasteboard()
        let sched = FakeScheduler()
        var posts: [Int] = []

        let paster = Paster(
            pasteboard: pb,
            postCmdV: { posts.append(1) },
            schedule: sched.schedule,
            restoreDelay: 2.0
        )

        try paster.paste("nuevo texto")

        XCTAssertEqual(pb.items.first?[text], Data("nuevo texto".utf8))
        XCTAssertEqual(posts, [1])
        XCTAssertEqual(sched.pending, 1)
        XCTAssertEqual(sched.delays, [2.0])

        sched.fire()
        XCTAssertEqual(pb.items, [[text: Data("old stuff".utf8)]])
    }

    func test_restore_skipped_if_user_copied_meanwhile() throws {
        let pb = FakePasteboard()
        let sched = FakeScheduler()

        let paster = Paster(
            pasteboard: pb,
            postCmdV: {},
            schedule: sched.schedule,
            restoreDelay: 2.0
        )

        try paster.paste("nuevo")
        let userCopy = [[text: Data("user copied this".utf8)]]
        pb.userCopies(userCopy)
        sched.fire()

        XCTAssertEqual(pb.items, userCopy)
    }

    func test_post_failure_raises_and_keeps_text_on_clipboard() throws {
        let pb = FakePasteboard()
        let sched = FakeScheduler()

        let paster = Paster(
            pasteboard: pb,
            postCmdV: {
                let error = NSError(domain: "test", code: 1, userInfo: [NSLocalizedDescriptionKey: "secure input"])
                throw error
            },
            schedule: sched.schedule,
            restoreDelay: 2.0
        )

        XCTAssertThrowsError(try paster.paste("texto")) { error in
            XCTAssertTrue(error is PasteError)
            if let pasteError = error as? PasteError {
                XCTAssertTrue(pasteError.message.contains("secure input"))
            }
        }

        XCTAssertEqual(pb.items.first?[text], Data("texto".utf8))
        XCTAssertEqual(sched.pending, 0)
    }

    func test_restores_non_text_clipboard_after_delay() throws {
        let png = ["public.png": Data([0x89, 0x50, 0x4E, 0x47])]
        let pb = FakePasteboard(items: [png])
        let sched = FakeScheduler()
        let paster = Paster(pasteboard: pb, postCmdV: {}, schedule: sched.schedule, restoreDelay: 2.0)

        try paster.paste("hello")
        XCTAssertEqual(pb.items.first?[text], Data("hello".utf8))

        sched.fire()
        XCTAssertEqual(pb.items, [png])
    }

    func test_dictation_is_marked_transient() throws {
        let pb = FakePasteboard(items: [])
        let paster = Paster(pasteboard: pb, postCmdV: {}, schedule: { _, _ in }, restoreDelay: 2.0)

        try paster.paste("hello")

        XCTAssertNotNil(pb.items.first?["org.nspasteboard.TransientType"])
        XCTAssertNotNil(pb.items.first?["org.nspasteboard.AutoGeneratedType"])
    }

    func test_empty_clipboard_schedules_no_restore() throws {
        let pb = FakePasteboard(items: [])
        let sched = FakeScheduler()
        let paster = Paster(pasteboard: pb, postCmdV: {}, schedule: sched.schedule, restoreDelay: 2.0)

        try paster.paste("hello")

        XCTAssertEqual(sched.pending, 0)
    }

    func test_back_to_back_dictations_restore_the_users_original() throws {
        let original = [[text: Data("mine".utf8)]]
        let pb = FakePasteboard(items: original)
        let sched = FakeScheduler()
        let paster = Paster(pasteboard: pb, postCmdV: {}, schedule: sched.schedule, restoreDelay: 2.0)

        try paster.paste("first")
        try paster.paste("second")  // within restoreDelay: the clipboard still holds "first"
        sched.fireAll()

        XCTAssertEqual(pb.items, original)
    }

    func test_restore_keeps_concealed_marker_and_nothing_transient() throws {
        let secret = [[text: Data("pw".utf8), "org.nspasteboard.ConcealedType": Data()]]
        let pb = FakePasteboard(items: secret)
        let sched = FakeScheduler()
        let paster = Paster(pasteboard: pb, postCmdV: {}, schedule: sched.schedule, restoreDelay: 2.0)

        try paster.paste("hello")
        sched.fire()

        XCTAssertEqual(pb.items, secret)
        XCTAssertNil(pb.items.first?["org.nspasteboard.TransientType"])
    }

    func test_clipboard_is_snapshotted_afresh_after_a_restore() throws {
        let first = [[text: Data("one".utf8)]]
        let second = [[text: Data("two".utf8)]]
        let pb = FakePasteboard(items: first)
        let sched = FakeScheduler()
        let paster = Paster(pasteboard: pb, postCmdV: {}, schedule: sched.schedule, restoreDelay: 2.0)

        try paster.paste("dictation 1")
        sched.fire()
        XCTAssertEqual(pb.items, first)

        // pending was cleared by the restore: a new copy must be what the next paste restores.
        pb.userCopies(second)
        try paster.paste("dictation 2")
        sched.fire()
        XCTAssertEqual(pb.items, second)
    }
}
