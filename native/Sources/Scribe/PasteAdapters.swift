/// `NSPasteboard.general` adapter. Untested: it would clobber the real clipboard.
final class MacPasteboard: PasteboardLike {
    private let pasteboard = NSPasteboard.general
    /// Above this the snapshot keeps only plain text: copying a huge image on every dictation is not worth it.
    private static let snapshotByteCap = 32 * 1024 * 1024

    func snapshot() -> [PasteboardItemData]? {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return nil }
        var out: [PasteboardItemData] = []
        var bytes = 0
        for item in items {
            var dict: PasteboardItemData = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    dict[type.rawValue] = data
                    bytes += data.count
                }
            }
            if !dict.isEmpty { out.append(dict) }
        }
        if bytes > Self.snapshotByteCap {
            let text = out.compactMap { $0[NSPasteboard.PasteboardType.string.rawValue] }.first
            return text.map { [[NSPasteboard.PasteboardType.string.rawValue: $0]] }
        }
        return out.isEmpty ? nil : out
    }

    func restore(_ items: [PasteboardItemData]) {
        pasteboard.clearContents()
        pasteboard.writeObjects(items.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict {
                item.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
            return item
        })
    }

    func setTransient(_ s: String) {
        // .currentHostOnly keeps the dictation off Universal Clipboard; the markers below only cover history apps.
        _ = pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(s, forType: .string)
        // nspasteboard.org markers: history apps (Maccy, Paste, …) skip items that carry them.
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
    }

    /// A deliberate user copy (History menu): plain, not transient, so clipboard managers may keep it.
    func set(_ s: String) {
        pasteboard.clearContents()
        pasteboard.setString(s, forType: .string)
    }

    func changeCount() -> Int {
        pasteboard.changeCount
    }
}

/// Posts a synthetic ⌘V. Untested: needs Accessibility and would hit the frontmost app.
func postCmdV() throws {
    guard
        let keyDown = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: true),
        let keyUp = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: false)
    else {
        throw PasteError(message: "could not create synthetic \u{2318}V key event")
    }

    keyDown.flags = .maskCommand
    keyUp.flags = .maskCommand

    keyDown.post(tap: .cghidEventTap)
    keyUp.post(tap: .cghidEventTap)
}

func timerSchedule(_ delaySeconds: Double, _ fn: @escaping () -> Void) {
    DispatchQueue.main.asyncAfter(deadline: .now() + delaySeconds, execute: fn)
}

enum Sounds {
    static func play(_ name: String) {
        NSSound(named: name)?.play()
    }
}

/// `SMAppService` login item. Untested: no fake seam, and it would pollute the test runner's login items.
enum LoginItem {
    static func enable() throws {
        do {
            try SMAppService.mainApp.register()
        } catch {
            throw LoginItemError(message: "could not register login item: \(error)")
        }
    }

    static func disable() throws {
        do {
            try SMAppService.mainApp.unregister()
        } catch {
            throw LoginItemError(message: "could not unregister login item: \(error)")
        }
    }

    static var isEnabled: Bool {
        SMAppService.mainApp.status == .enabled
    }
}
